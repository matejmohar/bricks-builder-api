#!/usr/bin/env node
// Renders compat/matrix.json (capability -> { bricksVersion: "pass" | "fail" }) to COMPATIBILITY.md.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const matrixPath = resolve(root, process.argv[2] ?? 'compat/matrix.json');
const outPath = resolve(root, process.argv[3] ?? 'COMPATIBILITY.md');

const matrix = JSON.parse(readFileSync(matrixPath, 'utf8'));
const capabilities = Object.keys(matrix);
const cmp = (a, b) => {
  const pa = a.split(/[.-]/).map((n) => Number.parseInt(n, 10) || 0);
  const pb = b.split(/[.-]/).map((n) => Number.parseInt(n, 10) || 0);
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
    if ((pa[i] ?? 0) !== (pb[i] ?? 0)) return (pb[i] ?? 0) - (pa[i] ?? 0); // newest first
  }
  return 0;
};
const versions = [...new Set(capabilities.flatMap((c) => Object.keys(matrix[c])))].sort(cmp);
const cell = (v) => (v === 'pass' ? 'pass' : v === 'fail' ? '**FAIL**' : '–');

const lines = [
  '# Compatibility',
  '',
  '<!-- Generated by scripts/render-compat.mjs from compat/matrix.json. Do not edit by hand. -->',
  '',
  'Results of the end-to-end compatibility check (`test/e2e/compat.spec.ts`) against real Bricks',
  'builder installs. Each capability is exercised in the builder; undoable actions also verify one',
  'history entry, undo and redo. "–" means not tested on that version.',
  '',
  `| Capability | ${versions.map((v) => `Bricks ${v}`).join(' | ')} |`,
  `| --- | ${versions.map(() => ':---:').join(' | ')} |`,
  ...capabilities.map((c) => `| \`${c}\` | ${versions.map((v) => cell(matrix[c][v])).join(' | ')} |`),
  '',
  'To add a version: run `npm run test:e2e` against a site with that Bricks version',
  '(`BRICKS_URL=...`), then `npm run compat`.',
  '',
];
writeFileSync(outPath, lines.join('\n'));
console.log(`Wrote ${outPath} (${capabilities.length} capabilities x ${versions.length} versions)`);
